export type IdeaTopic = keyof typeof drafts;

export function isDiscoveredIdea(id: string) {
  return /^(tiktok|telegram)-discovered-[a-f0-9]{24}$/.test(id);
}

export function ideaDraft(topic: string) {
  if (!Object.hasOwn(drafts, topic)) return undefined;
  const { title, angle } = drafts[topic as IdeaTopic];
  return { title, body: '# ' + title + '\n\n' + angle };
}
